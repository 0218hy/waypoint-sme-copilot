// Generate TypeScript types from the JSON Schemas exported by `agent/widgets.py`.
// The schemas use JSON Schema 2020-12 tuples (`prefixItems`); json-schema-to-typescript
// understands the draft-07 form (`items: [...]`), so tuples are rewritten before compiling.
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const dir = fileURLToPath(new URL('../src/contracts/', import.meta.url))

// Property-level `title`s would each become a named type alias (Label1, Label2, ...); drop them
// so only the models in `$defs` get names. Keys inside `properties` are field names, not keywords.
const TYPED = ['type', 'anyOf', 'oneOf', 'allOf', '$ref', 'enum', 'const', 'properties', 'items', 'prefixItems']

function rewrite(node, isModel = false) {
  if (Array.isArray(node)) return node.map((n) => rewrite(n))
  if (!node || typeof node !== 'object') return node
  const out = {}
  for (const [k, v] of Object.entries(node)) {
    if (k === 'title' && !isModel) continue
    if (k === '$defs') {
      out[k] = Object.fromEntries(Object.entries(v).map(([n, d]) => [n, rewrite(d, true)]))
    } else if (k === 'properties' || k === 'patternProperties') {
      out[k] = Object.fromEntries(Object.entries(v).map(([n, d]) => [n, rewrite(d)]))
    } else {
      out[k] = rewrite(v)
    }
  }
  // An untyped schema (pydantic `Any`) means any JSON value, not an object.
  if (!isModel && !TYPED.some((t) => t in out) && Object.keys(out).every((k) => ['default', 'description'].includes(k))) {
    out.tsType = 'unknown'
  }
  // JSON Schema 2020-12 tuples -> draft-07 form understood by json-schema-to-typescript.
  if (Array.isArray(out.prefixItems)) {
    out.items = out.prefixItems
    out.additionalItems = false
    delete out.prefixItems
  }
  return out
}

const banner = '/* eslint-disable */\n// Generated by `npm run contracts` from src/contracts/*.schema.json. Do not edit.\n'
let ts = banner
for (const name of ['widget', 'widget_event']) {
  const schema = rewrite(JSON.parse(await readFile(`${dir}${name}.schema.json`, 'utf8')), true)
  ts += '\n' + (await compile(schema, schema.title, {
    bannerComment: '',
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    format: true,
  }))
}
await writeFile(`${dir}types.ts`, ts)
console.log(`wrote ${dir}types.ts`)
